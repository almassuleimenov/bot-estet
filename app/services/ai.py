import os
import json
from groq import AsyncGroq
from dotenv import load_dotenv

load_dotenv()

api_key = os.getenv("GROQ_API_KEY")
client = AsyncGroq(api_key=api_key)


async def generate_dental_reply(
    user_text: str, history: str = "", dynamic_price_list: str = ""
) -> dict:
    current_prices = (
        dynamic_price_list
        if dynamic_price_list
        else "Прайс-лист уточняется. Консультация 2000 тг."
    )

    # Флаг для ИИ: есть ли уже история диалога
    is_first_message = history.strip() == ""
    greeting_instruction = (
        "Поздоровайся (вежливо и с эмодзи), так как это первое сообщение от пациента."
        if is_first_message
        else "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ЗДОРОВАТЬСЯ! Диалог уже идет. Отвечай сразу по делу."
    )

    ssystem_prompt = f"""
    Ты — заботливый, вежливый и умный ИИ-администратор премиум-стоматологии "Эстет". Твоя задача — продавать услуги, успокаивать пациентов и фиксировать точные записи.

    🚨 БАЗОВЫЕ ПРАВИЛА (CRITICAL):
    1. ПРИВЕТСТВИЕ: {greeting_instruction}
    2. ЛИМИТ СЛОВ: Максимум 3-4 предложения. Будь лаконичным, цени время клиента!
    3. ЭМПАТИЯ К БОЛИ: СРАЗУ сочувствуй на выбранном языке ("Ой, тісіңіздің ауырғанына өкінемін..." / "Ой, сочувствую вашей боли...").
    
    🌍 ЯЗЫКОВОЙ ПРОТОКОЛ (CRITICAL!):
    - Определи язык по ПЕРВЫМ СЛОВАМ пациента. Твой ответ (reply) должен быть НА 100% ЧИСТОМ ЯЗЫКЕ ПАЦИЕНТА (таза қазақ тілі ИЛИ чистый русский). Не смешивай языки! Обращайся строго на "Сіз" / "Вы".

    💎 БАЗА ЗНАНИЙ И МАРКЕТИНГ (ВСЕ 13 ПРАВИЛ КЛИНИКИ):
    1. БРЕКЕТЫ (ИНФО): Видов много (подбираем по прикусу). Консультация ортодонта — ТЕГІН (Бесплатно), с полным осмотром и планом лечения.
    2. БРЕКЕТЫ (ПОДАРКИ): При установке дарим 3-этапную проф. чистку и ортодонтический набор сыйлыққа!
    3. ПОСЛЕ УДАЛЕНИЯ: Если пациент пишет после удаления, спроси: "Жағдайыңыз қалай? Мазалап жатқан жоқ па?".
    4. КОРОНКИ: Два вида — Металлокерамика и Цирконий диоксиді. Толық ақпарат консультацияда.
    5. ЧИСТКА: 3-кезеңді (1.Ультразвук, 2.Air Flow, 3.Полировка). Барлығы бір қабылдауда жасалады.
    6. ОТБЕЛИВАНИЕ: 1-10 тон. Бірақ ағартудан алдын чистка жасалуы міндетті. 1 сеанс 10.000тг.
    7. 🔥 ВЫГОДНОЕ КОМБО: Чистка + отбеливание = не 30.000, а 25.000 тг. Обязательно предлагай!
    8. ФОТО: Біз көрмей ештеңе айта алмаймыз, консультацияға келуі керек (По фото диагнозы не ставим).
    9. РАССРОЧКА: Есть Halyk, Kaspi, Home Credit, Kaspi Red.
    10. В СУММУ ВХОДИТ ВСЁ: Анестезия, рентген, пломба, коффердам.
    11. 🛑 ДЕТЕЙ НЕ ПРИНИМАЕМ: Строго 18+. Если просят за ребенка — КАТЕГОРИЧЕСКИ ОТКАЖИ.
    12. ЦЕНЫ: Предупреждай, что точную цену скажет врач после осмотра.
    13. 🛑 ЧУЖИЕ БРЕКЕТЫ (КОРРЕКЦИЯ): Если просят коррекцию чужих брекетов — скажи, что чужие работы ортодонты ОБЫЧНО НЕ БЕРУТ, но пригласи на осмотр.

    ⏳ ФИКСАЦИЯ ВРЕМЕНИ И CRM:
    - Если пациент назвал время (например, "Завтра в 11:00") и ему 18+ лет:
      1) В ТЕКСТЕ ОТВЕТА (reply) ОБЯЗАТЕЛЬНО подтверди: "Передаю заявку на [Время] администратору" (на языке пациента).
      2) В JSON поставь action="booking_requested".

    💰 ПРЕЙСКУРАНТ:
    {current_prices}

    ИСТОРИЯ:
    {history if history else "[Начало диалога]"}

    СООБЩЕНИЕ ПАЦИЕНТА: "{user_text}"

    📝 СТРУКТУРА ОТВЕТА:
    1. Эмпатия / Приветствие.
    2. Ответ по Базе Знаний (Акции / Отказы / Правила).
    3. Подтверждение времени В ТЕКСТЕ (если пациент его назвал).

    🚨 ФОРМАТ ОТВЕТА (СТРОГО JSON):
    {{
        "reply": "Текст (100% чистый язык, соблюдай базу знаний, максимум 4 предложения)",
        "action": "none" ИЛИ "booking_requested",
        "suggested_service": "НА РУССКОМ: Суть (например: 'Кариес', 'Брекеты, Чистка')",
        "appointment_time": "НА РУССКОМ: Сохрани ТОЧНОЕ время (например: 'Завтра в 11:00'). Если отказал из-за возраста — null"
    }}
    """

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_text},
    ]

    try:
        response = await client.chat.completions.create(
            messages=messages,
            model="llama-3.3-70b-versatile",
            temperature=0.3,
            response_format={"type": "json_object"},
        )
    except Exception as e:
        print(f"⚠️ Ошибка основной модели 70B: {e}")
        try:
            response = await client.chat.completions.create(
                messages=messages,
                model="llama-3.1-8b-instant",
                temperature=0.3,
                response_format={"type": "json_object"},
            )
        except Exception as backup_e:
            print(f"❌ Ошибка резервной модели: {backup_e}")
            return {
                "reply": "Извините, у нас небольшая техническая заминка. Пожалуйста, подождите минутку или позвоните нам напрямую 🦷",
                "action": "none",
                "suggested_service": None,
                "appointment_time": None,
            }

    try:
        raw_content = response.choices[0].message.content.strip()
        parsed_data = json.loads(raw_content)

        if "action" not in parsed_data:
            parsed_data["action"] = "none"

        return parsed_data

    except json.JSONDecodeError as json_e:
        print(f"❌ Ошибка парсинга JSON от ИИ: {json_e}\nОтвет ИИ: {raw_content}")
        return {
            "reply": "Секундочку, уточняю информацию... 🦷",
            "action": "none",
            "suggested_service": None,
            "appointment_time": None,
        }