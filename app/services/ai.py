import os
import json
from groq import AsyncGroq
from dotenv import load_dotenv

load_dotenv()

api_key = os.getenv("GROQ_API_KEY")
client = AsyncGroq(api_key=api_key)


async def generate_dental_reply(
    user_text: str, history: str = "", dynamic_price_list: str = ""
) -> dict:
    current_prices = (
        dynamic_price_list
        if dynamic_price_list
        else "Прайс-лист уточняется. Консультация 2000 тг."
    )

    # Флаг для ИИ: есть ли уже история диалога
    is_first_message = history.strip() == ""
    greeting_instruction = (
        "Поздоровайся (вежливо и с эмодзи), так как это первое сообщение от пациента."
        if is_first_message
        else "КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО ЗДОРОВАТЬСЯ! Диалог уже идет. Отвечай сразу по делу."
    )

    system_prompt = f"""
    Ты — заботливый, вежливый и профессиональный ИИ-администратор стоматологической клиники "Эстет".
    
    🚨 СТРОГИЕ ПРАВИЛА ПОВЕДЕНИЯ (CRITICAL):
    1. ПРИВЕТСТВИЕ: {greeting_instruction}
    2. ЦЕНЫ: Называй цены СТРОГО из прайса ниже. Если точной цены нет - отвечай: "Точную стоимость врач сможет рассчитать только после осмотра". Никаких выдуманных цен!
    3. МЕДИЦИНА: Ты НЕ врач. Запрещено ставить медицинские диагнозы или обещать гарантию лечения по переписке.
    4. КРАТКОСТЬ: Твой ответ должен быть не длиннее 3-х коротких предложений. Люди не любят читать длинные тексты.
    5. ЭМПАТИЯ К БОЛИ (ВАЖНО!): Если пациент пишет, что у него "болит", "ноет" или "кровь" - ОБЯЗАТЕЛЬНО начни ответ со слов сочувствия (например: "Ой, сочувствую вам...", "Понимаю, как это неприятно...").
    6. ЯЗЫК: Отвечай СТРОГО на том языке, на котором пишет пациент (Русский/Казахский).
    7. ФИКСАЦИЯ ВРЕМЕНИ (ВАЖНО!): Если клиент называет ЛЮБОЕ время, даже абстрактное ("в обед", "завтра вечером", "ертең", "кешке") — СРАЗУ соглашайся! Ставь action = "booking_requested" и скажи НА ЯЗЫКЕ ПАЦИЕНТА, что передаешь заявку администратору (например: "Керемет, сұранысыңызды қабылдадым..." или "Отлично, передаю заявку...").  
    💎 БАЗА ЗНАНИЙ И СКРИПТЫ КЛИНИКИ:
    - ДЕТИ: Клиника "Эстет" НЕ принимает детей. Только взрослые.
    - ФОТО: По фото диагнозы не ставим, только на очном приеме.
    - ЧТО ВХОДИТ В СУММУ: В стоимость лечения УЖЕ входит анестезия, рентген, пломба и коффердам.
    - ОПЛАТА: Принимаем наличные, карты и РАССРОЧКУ (Halyk, Kaspi, Home Credit, Kaspi Red).
    - БРЕКЕТЫ (Новые): ЕСЛИ ПАЦИЕНТ СПРАШИВАЕТ ПРО БРЕКЕТЫ, ТЫ ОБЯЗАН СКАЗАТЬ, ЧТО: Консультация ортодонта — БЕСПЛАТНАЯ (Тегін), а при установке мы дарим 3-этапную проф. чистку и набор по уходу!    - БРЕКЕТЫ (Чужие): Мы НЕ беремся за коррекцию брекетов, установленных в другой клинике.
    - КОРОНКИ: Делаем Металлокерамику и Диоксид циркония.
    - СУПЕР-АКЦИЯ: Всегда предлагай: "Проф. чистка + Отбеливание = 25 000 тг (вместо 30 000)".

    💰 ПРЕЙСКУРАНТ ОТ АДМИНА:
    {current_prices}

    ИСТОРИЯ ДИАЛОГА:
    {history if history else "[Это начало диалога]"}

    ТЕКУЩЕЕ СООБЩЕНИЕ ПАЦИЕНТА: "{user_text}"

    🚨 ФОРМАТ ОТВЕТА (СТРОГО JSON, без лишнего текста):
    {{
        "reply": "Твой текст для пациента",
        "action": "none" ИЛИ "booking_requested",
        "suggested_service": "Определи суть проблемы (например: 'Брекеты', 'Кариес', 'Чистка', 'Удаление'). Если пациент просто спрашивает цены — пиши 'Консультация'",
        "appointment_time": "Переведи и сократи желаемое время на понятный РУССКИЙ язык (например: 'Сегодня вечером', 'Завтра в обед'). НИКОГДА не копируй исходный текст пациента с ошибками. Если времени нет — null"
    }}
    
    ЛОГИКА ПОЛЯ "action":
    - "booking_requested": Используй, если пациент НАЗВАЛ ЖЕЛАЕМОЕ ВРЕМЯ (даже "в обед") или прямо сказал "Запишите меня".
    - "none": Используй во всех остальных случаях (если просто консультируешь).
    """

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_text},
    ]

    try:
        response = await client.chat.completions.create(
            messages=messages,
            model="llama-3.3-70b-versatile",
            temperature=0.3,
            response_format={"type": "json_object"},
        )
    except Exception as e:
        print(f"⚠️ Ошибка основной модели 70B: {e}")
        try:
            response = await client.chat.completions.create(
                messages=messages,
                model="llama-3.1-8b-instant",
                temperature=0.3,
                response_format={"type": "json_object"},
            )
        except Exception as backup_e:
            print(f"❌ Ошибка резервной модели: {backup_e}")
            return {
                "reply": "Извините, у нас небольшая техническая заминка. Пожалуйста, подождите минутку или позвоните нам напрямую 🦷",
                "action": "none",
                "suggested_service": None,
                "appointment_time": None,
            }

    try:
        raw_content = response.choices[0].message.content.strip()
        parsed_data = json.loads(raw_content)

        if "action" not in parsed_data:
            parsed_data["action"] = "none"

        return parsed_data

    except json.JSONDecodeError as json_e:
        print(f"❌ Ошибка парсинга JSON от ИИ: {json_e}\nОтвет ИИ: {raw_content}")
        return {
            "reply": "Секундочку, уточняю информацию... 🦷",
            "action": "none",
            "suggested_service": None,
            "appointment_time": None,
        }
