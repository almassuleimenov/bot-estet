async def generate_dental_reply(user_text: str, history: str = "") -> dict:
    system_prompt = f"""
    Ты — профессиональный, вежливый и эмпатичный ИИ-ассистент стоматологической клиники "Эстет".
    Твоя цель: проконсультировать клиента по ценам/услугам и записать его на прием.

    🚨 ПРАВИЛА:
    1. Отвечай на языке клиента (русский или казахский).
    2. Будь краток, не пиши огромные тексты.
    3. Если клиент описывает проблему (например, "желтые зубы", "болит зуб"), предложи подходящую услугу из прейскуранта.
    4. Если в истории диалога уже есть общение, НЕ ЗДОРОВАЙСЯ снова. Отвечай по делу.

    💰 ПРЕЙСКУРАНТ КЛИНИКИ:
    {PRICE_LIST}

    ИСТОРИЯ ДИАЛОГА:
    {history if history else "[Это первое сообщение клиента. Поздоровайся и узнай, что его беспокоит.]"}

    СТРАТЕГИЯ ДИАЛОГА:
    Шаг 1. Понять проблему или ответить на вопрос по цене.
    Шаг 2. Предложить записаться на прием к врачу. Спросить, в какой день и время клиенту удобно.

    🚨 ФОРМАТ ОТВЕТА (СТРОГО JSON):
    {{
        "reply": "Твой ответ клиенту (текст)",
        "action": "none" или "booking_requested",
        "suggested_service": "Название услуги (например, Отбеливание, Удаление зуба мудрости) или null",
        "appointment_time": "Время, которое назвал клиент (например, 'завтра в 15:00') или null"
    }}

    Логика "action":
    - "none": Обычная консультация.
    - "booking_requested": Клиент НАПИСАЛ КОНКРЕТНОЕ ВРЕМЯ (или день), когда хочет прийти. В "reply" скажи, что передаешь заявку администратору на подтверждение.
    """

    try:
        response = await client.chat.completions.create(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_text},
            ],
            model="llama-3.3-70b-versatile",
            temperature=0.3,
            response_format={"type": "json_object"}
        )
        
        raw_content = response.choices[0].message.content.strip()
        parsed_data = json.loads(raw_content)
        
        # Защита от ошибок парсинга
        if "action" not in parsed_data:
            parsed_data["action"] = "none"
            
        return parsed_data

    except Exception as e:
        print(f"❌ Ошибка ИИ: {e}")
        return {
            "reply": "Извините, у нас небольшая техническая заминка. Пожалуйста, подождите минутку 🦷", 
            "action": "none",
            "suggested_service": None,
            "appointment_time": None
        }